"""A club's manual ledger (REQ-022): what members owe, what was received, and how it was matched.

Amounts are integer minor units with their currency. Nothing here processes payments: staff record money
received outside Coast TT. Records are never edited or deleted; a mistake is reversed with a reason and
the original stays. Balances are worked out from the records that stand.
"""

import uuid

from django.conf import settings
from django.db import models
from django.db.models import F, Q

USER = settings.AUTH_USER_MODEL


class Charge(models.Model):
    """Something a member owes the organization: an event fee, a booking, a due or anything else."""

    class Kind(models.TextChoices):
        EVENT_FEE = "event_fee", "Event fee"
        BOOKING = "booking", "Booking"
        DUE = "due", "Due"
        VISIT = "visit", "Facility visit"
        WELFARE = "welfare", "Welfare contribution"
        OTHER = "other", "Other"

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    organization = models.ForeignKey(
        "organizations.Organization", on_delete=models.CASCADE, related_name="charges"
    )
    # Nobody's account for a facility walk-in (REQ-044): their name is kept for the facility only.
    member = models.ForeignKey(USER, on_delete=models.PROTECT, null=True, blank=True, related_name="charges")
    walk_in_name = models.CharField(max_length=80, blank=True)
    kind = models.CharField(max_length=10, choices=Kind.choices, default=Kind.OTHER)
    purpose = models.CharField(max_length=120)
    amount_minor = models.PositiveIntegerField()
    currency = models.CharField(max_length=3, default="KES")
    due_on = models.DateField(null=True, blank=True)
    # What the charge is for, when it comes from elsewhere (a booking, a facility visit).
    source_id = models.UUIDField(null=True, blank=True)
    # A due generated by a contribution campaign, and the period (its first day) it is for.
    campaign = models.ForeignKey(
        "finance.Campaign", on_delete=models.PROTECT, null=True, blank=True, related_name="dues"
    )
    period = models.DateField(null=True, blank=True)
    waived_at = models.DateTimeField(null=True, blank=True)
    waived_by = models.ForeignKey(USER, on_delete=models.SET_NULL, null=True, blank=True, related_name="+")
    waive_reason = models.CharField(max_length=300, blank=True)
    created_by = models.ForeignKey(USER, on_delete=models.SET_NULL, null=True, related_name="+")
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["due_on", "created_at", "id"]
        indexes = [models.Index(fields=["organization", "member"])]
        constraints = [
            models.UniqueConstraint(
                fields=["kind", "source_id"],
                condition=Q(source_id__isnull=False),
                name="one_charge_per_source",
            ),
            # Generating a campaign's dues again never makes a second due for the same period.
            models.UniqueConstraint(
                fields=["campaign", "member", "period"],
                condition=Q(campaign__isnull=False),
                name="one_due_per_campaign_member_period",
            ),
        ]

    def __str__(self):
        return f"{self.purpose} {self.amount_minor} {self.currency}"


class Payment(models.Model):
    """Money received outside Coast TT, as staff recorded it. A reference helps reconcile but is not an
    identity: two payments can share one. `request_key` makes a retried request record nothing new."""

    class Method(models.TextChoices):
        CASH = "cash", "Cash"
        MPESA = "mpesa", "M-Pesa"
        BANK = "bank", "Bank transfer"
        OTHER = "other", "Other"

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    organization = models.ForeignKey(
        "organizations.Organization", on_delete=models.CASCADE, related_name="payments"
    )
    payer = models.ForeignKey(USER, on_delete=models.PROTECT, null=True, blank=True, related_name="payments")
    walk_in_name = models.CharField(max_length=80, blank=True)
    amount_minor = models.PositiveIntegerField()
    currency = models.CharField(max_length=3, default="KES")
    method = models.CharField(max_length=6, choices=Method.choices)
    reference = models.CharField(max_length=60, blank=True)
    received_on = models.DateField()
    request_key = models.UUIDField()
    recorded_by = models.ForeignKey(USER, on_delete=models.SET_NULL, null=True, related_name="+")
    created_at = models.DateTimeField(auto_now_add=True)
    reversed_at = models.DateTimeField(null=True, blank=True)
    reversed_by = models.ForeignKey(USER, on_delete=models.SET_NULL, null=True, blank=True, related_name="+")
    reversal_reason = models.CharField(max_length=300, blank=True)

    class Meta:
        ordering = ["-received_on", "-created_at"]
        constraints = [
            models.UniqueConstraint(fields=["organization", "request_key"], name="one_payment_per_request"),
            models.CheckConstraint(condition=Q(amount_minor__gt=0), name="payment_positive"),
        ]

    def __str__(self):
        return f"{self.amount_minor} {self.currency} from {self.payer_id}"


class Allocation(models.Model):
    """Part of a payment matched to a charge. A reversed payment's allocations no longer count."""

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    payment = models.ForeignKey(Payment, on_delete=models.PROTECT, related_name="allocations")
    charge = models.ForeignKey(Charge, on_delete=models.PROTECT, related_name="allocations")
    amount_minor = models.PositiveIntegerField()
    created_by = models.ForeignKey(USER, on_delete=models.SET_NULL, null=True, related_name="+")
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["created_at", "id"]
        constraints = [models.CheckConstraint(condition=Q(amount_minor__gt=0), name="allocation_positive")]

    def __str__(self):
        return f"{self.amount_minor} of {self.payment_id} to {self.charge_id}"


class Campaign(models.Model):
    """A purpose members contribute to (REQ-023): a one-time collection or a recurring due. Each period's
    dues are generated once per member as charges, with the amount as it was then; editing the campaign
    changes only periods not generated yet."""

    class Cadence(models.TextChoices):
        ONCE = "once", "One-time"
        WEEKLY = "weekly", "Weekly"
        MONTHLY = "monthly", "Monthly"
        QUARTERLY = "quarterly", "Quarterly"
        YEARLY = "yearly", "Yearly"

    class Audience(models.TextChoices):
        ALL = "all", "All active members"
        SELECTED = "selected", "Selected members"

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    organization = models.ForeignKey(
        "organizations.Organization", on_delete=models.CASCADE, related_name="campaigns"
    )
    title = models.CharField(max_length=120)
    description = models.TextField(blank=True)
    amount_minor = models.PositiveIntegerField()
    currency = models.CharField(max_length=3, default="KES")
    cadence = models.CharField(max_length=9, choices=Cadence.choices)
    # The first period's due date; later periods fall on the same weekday or day of the month, the day
    # clamped to the month's last (the 31st falls on 28 or 29 February, and back on 31 March).
    starts_on = models.DateField()
    ends_on = models.DateField(null=True, blank=True)
    audience = models.CharField(max_length=8, choices=Audience.choices, default=Audience.ALL)
    closed_at = models.DateTimeField(null=True, blank=True)
    created_by = models.ForeignKey(USER, on_delete=models.SET_NULL, null=True, related_name="+")
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["-created_at"]
        constraints = [models.CheckConstraint(condition=Q(amount_minor__gt=0), name="campaign_positive")]

    def __str__(self):
        return self.title


class CampaignMember(models.Model):
    """One member's terms in a campaign: included (for selected audiences), their own amount, or waived
    from future periods with a reason."""

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    campaign = models.ForeignKey(Campaign, on_delete=models.CASCADE, related_name="terms")
    member = models.ForeignKey(USER, on_delete=models.CASCADE, related_name="+")
    included = models.BooleanField(default=True)
    amount_minor = models.PositiveIntegerField(null=True, blank=True)
    waived = models.BooleanField(default=False)
    waive_reason = models.CharField(max_length=300, blank=True)

    class Meta:
        constraints = [
            models.UniqueConstraint(fields=["campaign", "member"], name="one_term_per_campaign_member")
        ]

    def __str__(self):
        return f"{self.member_id} in {self.campaign_id}"


class Expense(models.Model):
    """Money spent, on a campaign's purpose or the organization's general running (REQ-024). Kept for
    good: a mistake is reversed with a reason. The receipt is private to finance staff."""

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    organization = models.ForeignKey(
        "organizations.Organization", on_delete=models.CASCADE, related_name="expenses"
    )
    campaign = models.ForeignKey(
        Campaign, on_delete=models.PROTECT, null=True, blank=True, related_name="expenses"
    )
    welfare_project = models.ForeignKey(
        "finance.WelfareProject", on_delete=models.PROTECT, null=True, blank=True, related_name="expenses"
    )

    class Category(models.TextChoices):
        HALL_HIRE = "hall_hire", "Hall hire"
        EQUIPMENT = "equipment", "Equipment"
        WELFARE = "welfare", "Welfare"
        EVENTS = "events", "Events"
        TRANSPORT = "transport", "Transport"
        OTHER = "other", "Other"

    # What kind of spending it is, for the annual report (REQ-041), and who was paid.
    category = models.CharField(max_length=10, choices=Category.choices, default=Category.OTHER)
    payee = models.CharField(max_length=120, blank=True)
    description = models.CharField(max_length=200)
    amount_minor = models.PositiveIntegerField()
    currency = models.CharField(max_length=3, default="KES")
    spent_on = models.DateField()
    receipt = models.ForeignKey(
        "attachments.Attachment", on_delete=models.SET_NULL, null=True, blank=True, related_name="+"
    )
    recorded_by = models.ForeignKey(USER, on_delete=models.SET_NULL, null=True, related_name="+")
    created_at = models.DateTimeField(auto_now_add=True)
    reversed_at = models.DateTimeField(null=True, blank=True)
    reversed_by = models.ForeignKey(USER, on_delete=models.SET_NULL, null=True, blank=True, related_name="+")
    reversal_reason = models.CharField(max_length=300, blank=True)

    class Meta:
        ordering = ["-spent_on", "-created_at"]
        constraints = [models.CheckConstraint(condition=Q(amount_minor__gt=0), name="expense_positive")]

    def __str__(self):
        return f"{self.description} {self.amount_minor} {self.currency}"


class WelfareProject(models.Model):
    """A shared cause the club's members give to (REQ-038): supporting a sick or bereaved member, say.
    Giving is voluntary: the suggested amount never makes anyone owe. What the beneficiary's
    circumstances are is sensitive; staff write only what was agreed, and the beneficiary can have the
    project hidden."""

    class Audience(models.TextChoices):
        ALL = "all", "All active members"
        SELECTED = "selected", "Selected members"

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    organization = models.ForeignKey(
        "organizations.Organization", on_delete=models.CASCADE, related_name="welfare_projects"
    )
    title = models.CharField(max_length=120)
    description = models.TextField(blank=True)
    beneficiary = models.ForeignKey(USER, on_delete=models.SET_NULL, null=True, blank=True, related_name="+")
    suggested_minor = models.PositiveIntegerField(null=True, blank=True)
    currency = models.CharField(max_length=3, default="KES")
    target_minor = models.PositiveIntegerField(null=True, blank=True)
    deadline = models.DateField(null=True, blank=True)
    audience = models.CharField(max_length=8, choices=Audience.choices, default=Audience.ALL)
    audience_members = models.ManyToManyField(USER, blank=True, related_name="+")
    # The club may show who gave; each contributor can still stay anonymous in that list.
    show_contributors = models.BooleanField(default=False)
    # Set when staff make giving required (REQ-023): a one-time campaign whose dues count towards the
    # project. Until then nobody owes anything.
    campaign = models.OneToOneField(
        Campaign, on_delete=models.PROTECT, null=True, blank=True, related_name="welfare_project"
    )
    hidden_at = models.DateTimeField(null=True, blank=True)
    closed_at = models.DateTimeField(null=True, blank=True)
    created_by = models.ForeignKey(USER, on_delete=models.SET_NULL, null=True, related_name="+")
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["-created_at"]

    def __str__(self):
        return self.title


class WelfareContribution(models.Model):
    """One gift to a project: in the ledger as a payment matched in full to a paid welfare charge."""

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    project = models.ForeignKey(WelfareProject, on_delete=models.PROTECT, related_name="contributions")
    contributor = models.ForeignKey(USER, on_delete=models.PROTECT, related_name="+")
    payment = models.OneToOneField(Payment, on_delete=models.PROTECT, related_name="welfare")
    charge = models.OneToOneField(Charge, on_delete=models.PROTECT, related_name="welfare")
    anonymous = models.BooleanField(default=False)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["-created_at"]

    def __str__(self):
        return f"{self.contributor_id} to {self.project_id}"


class FinanceSettings(models.Model):
    """When the organization's financial year ends (REQ-041): 31 December unless it says otherwise."""

    organization = models.OneToOneField(
        "organizations.Organization", on_delete=models.CASCADE, related_name="finance_settings"
    )
    year_end_month = models.PositiveSmallIntegerField(default=12)
    year_end_day = models.PositiveSmallIntegerField(default=31)
    updated_by = models.ForeignKey(USER, on_delete=models.SET_NULL, null=True, related_name="+")
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        constraints = [
            models.CheckConstraint(
                condition=Q(
                    year_end_month__gte=1, year_end_month__lte=12, year_end_day__gte=1, year_end_day__lte=31
                ),
                name="finance_year_end_is_a_date",
            )
        ]

    def __str__(self):
        return f"Finance settings of {self.organization_id}"


class AnnualReport(models.Model):
    """The accounts of one financial year (REQ-041). A draft shows the ledger as it stands. Publishing
    freezes the figures in `snapshot` for good; a later correction is published as a new version that
    lists what changed, and the earlier versions stay."""

    class Status(models.TextChoices):
        DRAFT = "draft"
        PUBLISHED = "published"

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    organization = models.ForeignKey(
        "organizations.Organization", on_delete=models.CASCADE, related_name="annual_reports"
    )
    period_start = models.DateField()
    period_end = models.DateField()
    version = models.PositiveSmallIntegerField(default=1)
    amends = models.OneToOneField(
        "self", on_delete=models.PROTECT, null=True, blank=True, related_name="amended_by"
    )
    status = models.CharField(max_length=10, choices=Status.choices, default=Status.DRAFT)
    narrative = models.TextField(max_length=5000, blank=True)
    # Shown to everyone, signed in or not. Members always see a published report.
    public = models.BooleanField(default=False)
    # The figures as published, and for an amendment what differs from the version before.
    snapshot = models.JSONField(null=True, blank=True)
    changes = models.JSONField(default=list, blank=True)
    created_by = models.ForeignKey(USER, on_delete=models.SET_NULL, null=True, related_name="+")
    created_at = models.DateTimeField(auto_now_add=True)
    published_by = models.ForeignKey(USER, on_delete=models.SET_NULL, null=True, blank=True, related_name="+")
    published_at = models.DateTimeField(null=True, blank=True)

    class Meta:
        ordering = ["-period_end", "-version"]
        constraints = [
            models.UniqueConstraint(
                fields=["organization", "period_end", "version"], name="one_report_version_per_year"
            ),
            models.CheckConstraint(
                condition=Q(status="draft") | Q(snapshot__isnull=False, published_at__isnull=False),
                name="published_report_is_frozen",
            ),
            models.CheckConstraint(
                condition=Q(period_end__gt=F("period_start")), name="report_period_in_order"
            ),
        ]

    def __str__(self):
        return f"Report to {self.period_end} v{self.version}"
